"""Regenerate src/data/languages.master.ts from the Master Language List workbook.

Usage: python3 -I scripts/import-languages.py path/to/InterpretNext_Master_Language_List.xlsx

Reads the "Master Directory" sheet. Columns used: ID, Language, Native name, ISO 639 code,
Website region, Category, Locales/dialects/varieties, Staffable today, Service modes, Native reviewed.
Rows added by the website team (English, ASL) are appended at the end and marked source "web".
"""
import json, re, sys, pathlib
import openpyxl

src = sys.argv[1]
out = pathlib.Path(__file__).resolve().parent.parent / "src" / "data" / "languages.master.ts"
wb = openpyxl.load_workbook(src, data_only=True)
rows = list(wb["Master Directory"].iter_rows(values_only=True))
head = [str(h or "").strip() for h in rows[0]]
col = {h: i for i, h in enumerate(head)}

def g(r, name):
    v = r[col[name]] if name in col else None
    return "" if v is None else str(v).strip()

LOCALE = re.compile(r"^[a-z]{2,3}(-[A-Za-z0-9]+)+\s+")
def varieties(s):
    out = []
    for part in s.split(";"):
        part = part.strip()
        if not part:
            continue
        code = None
        m = LOCALE.match(part)
        if m:
            code = m.group(0).strip()
            part = part[m.end():].strip()
        out.append({"code": code, "label": part} if code else {"label": part})
    return out

def staff(s):
    s = s.lower()
    if not s: return None
    if s.startswith("yes") and "demand" in s: return "on-demand"
    if s.startswith("yes"): return "scheduled"
    if "request" in s: return "on-request"
    if s.startswith("no"): return "no"
    return None

langs = []
for r in rows[1:]:
    if not g(r, "ID") or not g(r, "Language"):
        continue
    item = {
        "id": g(r, "ID"),
        "name": g(r, "Language"),
        "iso": g(r, "ISO 639 code"),
        "region": g(r, "Website region"),
        "category": g(r, "Category"),
        "varieties": varieties(g(r, "Locales, dialects and varieties")),
        "staffable": staff(g(r, "Staffable today")),
    }
    if g(r, "Native name"): item["native"] = g(r, "Native name")
    if g(r, "Service modes"): item["modes"] = g(r, "Service modes")
    if g(r, "Native reviewed").lower().startswith("yes"): item["reviewed"] = True
    langs.append(item)

# Added by the website team, agreed 19 Nov 2026 (see docs/CONTENT-STATUS.md)
langs += [
    {"id": "W001", "name": "English", "iso": "en", "region": "Europe", "category": "Major",
     "varieties": [{"code": "en-US", "label": "United States"}, {"code": "en-GB", "label": "United Kingdom"},
                   {"code": "en-CA", "label": "Canada"}, {"code": "en-AU", "label": "Australia"}],
     "staffable": None, "native": "English", "source": "web"},
    {"id": "W002", "name": "American Sign Language", "iso": "ase", "region": "Americas", "category": "Sign language",
     "varieties": [{"label": "United States"}, {"label": "Canada (English-speaking)"}],
     "staffable": None, "native": "ASL", "source": "web", "confirm": True},
]

body = "[\n" + ",\n".join(" " + json.dumps(l, ensure_ascii=False, separators=(",", ":")) for l in langs) + "\n]"
out.write_text(
    "/* GENERATED by scripts/import-languages.py from the Master Language List. Do not edit by hand. */\n"
    'import type { MasterRow } from "./languages";\n\n'
    f"export const MASTER: MasterRow[] = {body};\n",
    encoding="utf-8",
)
print(f"wrote {len(langs)} languages to {out}")
